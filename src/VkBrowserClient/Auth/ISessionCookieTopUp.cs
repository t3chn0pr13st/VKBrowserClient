namespace VkBrowserClient;

/// <summary>
/// Дотягивает уже действующую сессию до домена, cookie которого в ней нет.
///
/// VK держит на каждом своём домене собственный набор cookie и передаёт сессию между ними сам,
/// но делает это на стороне клиента — обычным HTTP-запросом переход не воспроизвести (проверено:
/// домен отвечает <c>_ignoreAutoLogin</c> и авторизационной cookie не ставит). Настоящему браузеру
/// достаточно один раз открыть нужный домен, и повторный вход при этом не требуется.
///
/// Отдельный интерфейс, а не метод <see cref="IInteractiveAuthenticator"/>: серверные реализации
/// без браузера не обязаны это уметь, и не должны ломаться от появления возможности.
/// </summary>
public interface ISessionCookieTopUp
{
    /// <summary>
    /// Пытается добрать cookie указанного домена в переданную сессию.
    /// Возвращает <c>true</c>, если сессия была дополнена; вызывающий код сам её сохраняет.
    /// </summary>
    Task<bool> TopUpAsync(VkSession session, string host, CancellationToken cancellationToken = default);
}
